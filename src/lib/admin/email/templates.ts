export const fill = (s: string, vars: Record<string, string | number | null | undefined>) =>
  s.replace(/\{\{\s*(\w+)\s*\}\}/g, (_m, k: string) => (vars[k] === undefined || vars[k] === null ? "" : String(vars[k])));
